import pandas as pd
import matplotlib.pyplot as plt
from sklearn.preprocessing import StandardScaler
from sklearn.cluster import KMeans

# 1. Load the applicant profiles dataset
df_apps = pd.read_csv("credit_applicants.csv")

# 2. Select the numeric features to find behavioral groups
cluster_features = ["monthly_income_inr", "credit_utilization_ratio", "existing_loans_count"]
X_cluster = df_apps[cluster_features].copy()

# 3. Handle any blanks and scale the numbers so they match perfectly
X_cluster = X_cluster.fillna(X_cluster.median())
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X_cluster)

# 4. Run K-Means with an optimal k=3 behavioral groups
kmeans = KMeans(n_clusters=3, random_state=42, n_init=10)
df_apps["Behavior_Cluster"] = kmeans.fit_predict(X_scaled)

# 5. Check if any group over-indexes (has a higher rate) on defaults!
cluster_analysis = df_apps.groupby("Behavior_Cluster")["default"].mean() * 100

print("=== K-MEANS CUSTOMER SEGMENTATION RESULTS ===")
for cluster_num, default_rate in cluster_analysis.items():
    print(f"Group/Cluster {cluster_num}: Average Default Risk Rate is {default_rate:.2f}%")
