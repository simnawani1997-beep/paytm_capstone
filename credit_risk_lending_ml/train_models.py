features_to_use = ["txn_hour", "is_new_device", "txn_amount_inr"]
X_behavior = df_behavior[features_to_use]

# 3. Standardize the data numbers (this shrinks them so the algorithm reads them easily)
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X_behavior)

# 4. Configure scikit-learn's Isolation Forest algorithm
# We set the contamination to 5.7% to match your professor's exact mathematical rule
iso_forest = IsolationForest(contamination=0.057, random_state=42)

# Run the algorithm to flag anomalies (-1 means anomaly, 1 means safe)
df_behavior["predicted_anomaly"] = iso_forest.fit_predict(X_scaled)

# 5. Perform the Professor's required Recall Check!
# We extract the 15 true hidden attack rows (where transaction_id starts with 'BTXNA')
true_anomalies = df_behavior[df_behavior["txn_id"].str.startswith("BTXNA")]

# Count how many of those 15 rows our algorithm successfully caught (predicted as -1)
caught_count = (true_anomalies["predicted_anomaly"] == -1).sum()

print("=== ISOLATION FOREST ANOMALY PERFORMANCE LOG ===")
